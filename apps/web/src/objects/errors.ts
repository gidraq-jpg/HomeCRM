import { ApiError, errorMessage } from '../auth/api.ts';

// Тексты ответов API объектов (ADR-0023). Технические сообщения сервера не показываются. Каждое
// объяснение говорит, что делать дальше; названий, значений полей и текстов событий в них нет.

export type ObjectAction =
  | 'load'
  | 'create'
  | 'save'
  | 'trash'
  | 'restore'
  | 'share'
  | 'personal'
  | 'audience'
  | 'copy'
  | 'preview'
  | 'event'
  | 'link'
  | 'account'
  | 'contact'
  | 'meter'
  | 'replace'
  | 'reading'
  | 'transmit';

/** Запись изменили после того, как её открыли: правку нужно сверить с новой версией. */
export function isStaleVersion(error: unknown): boolean {
  return error instanceof ApiError && error.status === 409 && error.code === 'STALE_VERSION';
}

const INVALID: Readonly<Partial<Record<ObjectAction, string>>> = {
  event:
    'Проверьте событие: нужны дата и текст (до 10 000 знаков), сумма — в рублях, оценка — от 1 до 5.',
  link: 'Не удалось связать записи. Проверьте подпись: она не длиннее 200 знаков.',
  account:
    'Проверьте лицевой счёт: ссылки начинаются с http:// или https://, день — от 1 до 31, номер и название не длиннее 200 знаков.',
  contact:
    'Проверьте организацию: название обязательно (до 200 знаков), телефонов не больше 20, сайт — ссылка на http:// или https://.',
};

export function objectErrorMessage(error: unknown, action: ObjectAction): string {
  if (!(error instanceof ApiError)) return errorMessage(error);
  const { status, code } = error;
  if (status === 0 || status === 429) return errorMessage(error);
  if (status === 401) return 'Вход истёк. Войдите заново.';
  if (action === 'meter' || action === 'replace' || action === 'reading' || action === 'transmit') {
    return meterErrorMessage(error, action);
  }
  if (status === 404) {
    if (action === 'account') {
      return 'Не нашли лицевой счёт, объект или поставщика: их удалили или они стали вам недоступны. Обновите страницу.';
    }
    if (action === 'contact') {
      return 'Организации больше нет, или она стала вам недоступна. Вернитесь к списку и обновите его.';
    }
    return action === 'link' || action === 'event'
      ? 'Запись больше недоступна: её удалили или она стала вам недоступна. Обновите страницу.'
      : 'Объекта больше нет, или он стал вам недоступен. Вернитесь в «Дом» и обновите список.';
  }
  if (status === 403) {
    switch (action) {
      case 'personal':
        return 'Сделать объект личным нельзя: в нём есть правки других участников. Скопируйте его в личное.';
      case 'trash':
        return 'Убрать общий объект в корзину могут только взрослые.';
      case 'restore':
        return 'Вернуть общий объект из корзины может его автор-взрослый или администратор.';
      case 'share':
        return 'Поделиться можно только своим личным объектом.';
      case 'audience':
        return 'Менять, кто видит объект, могут только взрослые.';
      case 'link':
        return 'Связать записи нельзя: нужно право менять хотя бы одну из них.';
      case 'event':
        return 'Менять ленту этого объекта вам нельзя. Обновите страницу: возможно, права изменились.';
      case 'account':
        return 'Менять лицевые счета этого объекта могут только взрослые. Вернуть счёт из корзины может его автор-взрослый или администратор.';
      case 'contact':
        return 'Менять общие организации могут только взрослые. Вернуть организацию из корзины может её автор-взрослый или администратор.';
      default:
        return 'Это действие вам недоступно. Обновите страницу и повторите.';
    }
  }
  if (status === 409) {
    if (isStaleVersion(error)) {
      if (action === 'account' || action === 'contact') {
        return 'Запись изменили, пока вы её правили. Обновите страницу и повторите.';
      }
      return action === 'event'
        ? 'Событие изменили, пока вы его правили. Обновите ленту и повторите.'
        : 'Объект изменили, пока вы его правили. Обновите его и повторите.';
    }
    if (code === 'ASSIGNEE_CANNOT_SEE') {
      return 'Этот участник не увидит объект. Выберите ответственным того, кто его видит, а при доступе «Взрослые» — взрослого.';
    }
    if (code === 'CONFIRMATION_REQUIRED') return 'Нужно подтвердить действие. Повторите его.';
    return 'Данные изменились, пока вы работали. Обновите страницу и повторите.';
  }
  if (status === 400) {
    return (
      INVALID[action] ??
      'Проверьте объект: название обязательно и не длиннее 200 знаков; у каждого поля нужно название (до 100 знаков), значение — до 4000; полей не больше 50.'
    );
  }
  if (action === 'load') return 'Не удалось загрузить данные. Проверьте подключение и повторите.';
  return errorMessage(error);
}

/** Тексты счётчиков и показаний (ADR-0032): ни значений, ни номеров, ни названий в них нет. */
function meterErrorMessage(
  error: ApiError,
  action: 'meter' | 'replace' | 'reading' | 'transmit',
): string {
  const { status, code } = error;
  if (status === 404) {
    return 'Не нашли объект, счётчик или показание: их удалили или они стали вам недоступны. Обновите страницу.';
  }
  if (status === 403) {
    return 'Менять счётчики и вводить показания могут только взрослые. Обновите страницу: возможно, права изменились.';
  }
  if (isStaleVersion(error))
    return 'Счётчик изменили, пока вы его правили. Обновите страницу и повторите.';
  if (code === 'INVALID_READING') {
    return 'Одно из значений не подошло счётчику: оно меньше прошлого или длиннее, чем позволяет разрядность. Ничего не сохранено: проверьте цифры.';
  }
  if (code === 'READING_DATE_ORDER') {
    return 'У одного из счётчиков уже есть показание на эту дату или позже. Выберите более позднюю дату. Ничего не сохранено.';
  }
  if (code === 'METER_INACTIVE') {
    return 'Один из счётчиков заменён или снят, показания по нему не вводятся. Обновите страницу.';
  }
  if (code === 'INVALID_REPLACEMENT') {
    return 'Новый счётчик должен быть того же ресурса, а даты конечного и начального показаний совпадают. Ничего не сохранено.';
  }
  if (code === 'USE_METER_REPLACEMENT') {
    return 'Статус «заменён» ставит замена счётчика: воспользуйтесь кнопкой «Заменить счётчик».';
  }
  if (status === 409) {
    return action === 'transmit'
      ? 'Показания изменились, пока вы их передавали. Обновите страницу и повторите.'
      : 'Данные изменились, пока вы работали: например, зоны и разрядность после первого показания не меняются. Обновите страницу и повторите.';
  }
  if (status === 400) {
    return action === 'transmit'
      ? 'Не удалось отметить показания переданными. Обновите страницу и повторите.'
      : 'Проверьте счётчик: заводской номер, модель и место — до 200 знаков, зон от 1 до 3, цифр до запятой 1–12, после запятой 0–6, даты полностью.';
  }
  return errorMessage(error);
}
